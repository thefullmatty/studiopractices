function populateLists(){
  Object.entries(lists).forEach(([id, values]) => {
    const list = document.getElementById(id);
    values.forEach(value => {
      const option = document.createElement('option');
      option.value = value;
      list.appendChild(option);
    });
  });
}

const ids = ['site','action','location','documentation','journal','material1','material2','material3','surface1','surface2','surface3','tool1','tool2','tool3','other'];
const $ = (id) => document.getElementById(id);
const slot = (name) => document.querySelector(`[data-slot="${name}"]`);

function values(names){
  return names.map(id => $(id).value.trim()).filter(Boolean);
}
function joinNice(items){
  if(!items.length) return '';
  if(items.length === 1) return items[0];
  if(items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0,-1).join(', ')}, and ${items[items.length-1]}`;
}
function setSlot(name, text, fallback){
  const el = slot(name);
  const output = text || fallback;
  el.textContent = output;
  el.classList.toggle('muted', !text);
}
function updateEditor(){
  const materials = values(['material1','material2','material3']);
  const surfaces = values(['surface1','surface2','surface3']);
  const tools = values(['tool1','tool2','tool3']);
  const other = $('other').value.trim();
  const useParts = [];
  if(materials.length) useParts.push(joinNice(materials));
  if(tools.length) useParts.push(joinNice(tools));
  if(other) useParts.push(other);
  const workParts = [];
  if($('location').value.trim()) workParts.push($('location').value.trim());
  if(surfaces.length) workParts.push(joinNice(surfaces));
  setSlot('site', $('site').value.trim(), 'your site of inquiry');
  setSlot('action', $('action').value.trim(), 'a studio action');
  setSlot('use', joinNice(useParts), 'materials and tools');
  setSlot('work', joinNice(workParts), 'a surface or location');
  setSlot('documentation', $('documentation').value.trim(), 'a method of recording');
  setSlot('journal', $('journal').value.trim(), 'a reflective question');
}

function getSlotText(name){ return slot(name)?.textContent.trim() || ''; }
function getExtraLines(){
  return Array.from(document.querySelectorAll('.extra-line')).map(el => el.textContent.trim()).filter(Boolean);
}
function escapeHTML(str){
  return str.replace(/[&<>'"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[c]));
}

function makeCard(){
  const materials = joinNice(values(['material1','material2','material3'])) || 'as needed';
  const surfaces = joinNice(values(['surface1','surface2','surface3'])) || 'as needed';
  const tools = joinNice(values(['tool1','tool2','tool3'])) || 'as needed';
  const condition = $('other').value.trim() || 'none specified';
  const extra = getExtraLines();
  const extraHTML = extra.length ? extra.map(line => `<p>${escapeHTML(line)}</p>`).join('') : '';

  $('cardText').innerHTML = `
    <h2>My Recipe</h2>
    <h3>Ingredients</h3>
    <p><strong>Materials:</strong> ${escapeHTML(materials)}</p>
    <p><strong>Surface:</strong> ${escapeHTML(surfaces)}</p>
    <p><strong>Tools:</strong> ${escapeHTML(tools)}</p>
    <p><strong>Condition:</strong> ${escapeHTML(condition)}</p>
    <h3>Method</h3>
    <p><strong>Start with:</strong> ${escapeHTML(getSlotText('site'))}</p>
    <p><strong>Try:</strong> ${escapeHTML(getSlotText('action'))}</p>
    <p><strong>Work on/in:</strong> ${escapeHTML(getSlotText('work'))}</p>
    <p><strong>Document by:</strong> ${escapeHTML(getSlotText('documentation'))}</p>
    ${extraHTML}
    <h3>Reflection</h3>
    <p><strong>Write from:</strong> ${escapeHTML(getSlotText('journal'))}</p>
    <h3>Next</h3>
    <p>Decide what should be repeated, changed, removed, or developed.</p>`;
  $('movingCard').classList.add('is-visible');
  status('recipe card made');
}

function editorPlainText(){
  return Array.from(document.querySelectorAll('.recipe-line')).map(line => line.innerText.trim()).join('\n\n');
}
function cardPlainText(){
  return $('cardText').innerText.trim();
}
async function copyText(){
  const text = $('movingCard').classList.contains('is-visible') ? cardPlainText() : editorPlainText();
  try{
    await navigator.clipboard.writeText(text);
    status('copied');
  }catch(err){
    status('copy failed — select text manually');
  }
}
function safeFilename(text){
  const base = (text || 'studio-recipe')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 42);
  return `${base || 'studio-recipe'}.txt`;
}
function downloadRecipe(){
  makeCard();
  const text = cardPlainText();
  const site = getSlotText('site');
  const blob = new Blob([text + '\n'], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = safeFilename(site ? `studio-recipe-${site}` : 'studio-recipe');
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
  status('recipe downloaded');
}
function addExtra(kind){
  const nextLine = document.querySelector('.next-line');
  const div = document.createElement('div');
  div.className = 'recipe-line extra-line';
  const label = kind === 'step' ? 'Additional step:' : 'Constraint:';
  const suggestedText = kind === 'constraint' ? $('other').value.trim() : '';
  div.innerHTML = `<strong>${label}</strong><span class="slot" contenteditable="true" data-placeholder="write here">${escapeHTML(suggestedText)}</span>`;
  nextLine.parentNode.insertBefore(div, nextLine);
  const slot = div.querySelector('.slot');
  slot.addEventListener('input', () => {
    if (slot.innerHTML === '<br>') slot.innerHTML = '';
  });
  slot.focus();
}
function clearAll(){
  ids.forEach(id => $(id).value = '');
  document.querySelectorAll('.extra-line').forEach(el => el.remove());
  updateEditor();
  $('cardText').innerHTML = '<h2>My Recipe</h2><p>Build and edit your studio recipe, then make your card.</p>';
  $('movingCard').classList.remove('is-visible');
  status('cleared');
}
let statusTimer;
function status(message){
  $('status').textContent = message;
  clearTimeout(statusTimer);
  statusTimer = setTimeout(() => $('status').textContent = '', 2200);
}

function fitStage(){
  const viewport = $('viewport');
  const stage = $('stage');
  const scale = viewport.clientWidth / 1280;
  stage.style.transform = `scale(${scale})`;
  viewport.style.height = `${1024 * scale}px`;
}

